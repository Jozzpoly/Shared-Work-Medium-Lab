import assert from 'node:assert/strict';
import {chromium} from 'playwright';
import {fileURLToPath} from 'node:url';
import {mkdir} from 'node:fs/promises';
const source=fileURLToPath(new URL('./index.html',import.meta.url));
const browser=await chromium.launch({headless:true,executablePath:process.env.CHROME_BIN||'/usr/bin/google-chrome',args:['--no-sandbox']});
try{
  for(const viewport of [{width:1440,height:900},{width:390,height:844}]){
    const page=await browser.newPage({viewport});
    const failures=[],outgoing=[];
    page.on('pageerror',e=>failures.push(String(e)));
    page.on('request',r=>{if(!r.url().startsWith('file:'))outgoing.push(r.url());});
    await page.goto('file://'+source,{waitUntil:'load'});
    assert.match(await page.locator('#name').innerText(),/Combat Lab/);
    assert.equal(await page.locator('.node').count(),5);
    assert.equal(await page.locator('.seam').count(),5);
    await page.locator('[data-view="material"]').click();
    assert.match(await page.locator('#name').innerText(),/fizycznych/i);
    assert.equal(await page.locator('#source-links a').count(),2);
    assert.match(page.url(),/view=material/);
    await page.locator('button[data-lens="limits"]').click();
    assert.match(page.url(),/lens=limits/);
    assert.match(await page.locator('#detail').innerText(),/nie ma|nie udowodniono|nie jest/i);
    await page.reload();
    assert.equal(await page.locator('[data-view="material"]').getAttribute('aria-pressed'),'true');
    assert.equal(await page.locator('button[data-lens="limits"]').getAttribute('aria-pressed'),'true');
    await page.locator('[data-view="reflex"]').click();
    assert.match(await page.locator('#source-links a').last().getAttribute('href'),/research\/pre-o0-foundations-campaign/);
    assert.equal(await page.locator('.node[aria-pressed="true"]').count(),1);
    const overflow=await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth+1);
    assert.equal(overflow,false,viewport.width+'px horizontal overflow');
    assert.deepEqual(failures,[]);assert.deepEqual(outgoing,[]);
    await page.locator('[data-view="material"]').click();
    await page.locator('#enter-atelier').click();
    await page.waitForFunction(()=>document.querySelector('#left-state')?.textContent?.startsWith('ODCZYTANO')&&document.querySelector('#right-state')?.textContent?.startsWith('ODCZYTANO'),{timeout:25000});
    assert.equal(await page.locator('.source-results').count(),2);
    await page.locator('#trace').fill('__unlikely_no_hit_test_294841_XYZ__');
    assert.equal(await page.locator('#left-results button').count(),0);
    assert.equal(await page.locator('#left-pin').isDisabled(),true);
    await page.locator('#trace').fill('world');
    assert.ok(await page.locator('#left-results button').count()>0);
    assert.ok(await page.locator('#right-results button').count()>0);
    await page.locator('#left-results button').first().click();
    await page.locator('#left-pin').click();
    await page.locator('#right-results button').first().click();
    await page.locator('#right-pin').click();
    assert.equal(await page.locator('.clip').count(),2);
    await page.locator('#own-note').fill('Testowana analogia, nie potwierdzona integracja.');
    await page.locator('#make-note').click();
    await mkdir('/tmp/medium-world',{recursive:true});
    await page.screenshot({path:'/tmp/medium-world/'+viewport.width+'-atelier.png',fullPage:true});
    const report=await page.locator('#export-text').inputValue();
    assert.match(report,/Combat Lab/);assert.match(report,/FrameMatter/);
    assert.match(report,/github.com\/Jozzpoly\/Combat-Lab\/blob\//);
    assert.match(report,/github.com\/Jozzpoly\/FrameMatter-Lab\/blob\//);
    assert.ok(!/undefined|null/.test(report));
    await page.locator('#left-fresh').click();
    await page.waitForFunction(()=>/ZGODNA TREŚĆ|RÓŻNE DOKUMENTY|BRAK ODCZYTU/.test(document.querySelector('#left-fresh-state')?.textContent||''),{timeout:25000});
    assert.notEqual((await page.locator('#left-fresh-state').innerText()).length,0);
    assert.equal(outgoing.length,3);
    assert.ok(outgoing.every(u=>u.startsWith('https://raw.githubusercontent.com/Jozzpoly/')));
    assert.ok(outgoing.some(u=>u.includes('/Combat-Lab/main/docs/RESEARCH_STATE.md')));
    await page.locator('#pair-right').selectOption('npc');
    await page.locator('#apply-pair').click();
    await page.waitForFunction(()=>document.querySelector('#right-state')?.textContent?.startsWith('ODCZYTANO'),{timeout:25000});
    assert.match(await page.locator('#atelier-title').innerText(),/Combat Lab.*LLM Live NPC/);
    assert.equal(await page.locator('#right-name').innerText(),'LLM Live NPC');
    assert.equal(await page.locator('.clip').count(),2);
    await page.locator('#right-pin').click();
    await page.locator('#make-note').click();
    const custom=await page.locator('#export-text').inputValue();
    assert.match(custom,/Combat Lab ↔ LLM Live NPC/);
    assert.match(custom,/LLM Live NPC/);
    assert.ok(!custom.includes('Uczestnik zestawił źródła samodzielnie. Nie przypisano im uprzednio relacji ani wspólnej architektury.\n\n## Ślady\nNie wybrano'));
    assert.equal(outgoing.length,5);
    assert.ok(outgoing.every(u=>u.startsWith('https://raw.githubusercontent.com/Jozzpoly/')));
    await page.screenshot({path:'/tmp/medium-world/'+viewport.width+'-custom-pair.png',fullPage:true});
    await page.locator('#leave-atelier').click();
    assert.equal(await page.locator('.node:visible').count(),5);
    assert.deepEqual(failures,[]);
    await mkdir('/tmp/medium-world',{recursive:true});
    await page.screenshot({path:'/tmp/medium-world/'+viewport.width+'.png',fullPage:true});
    console.log('PASS real browser '+viewport.width+'px: navigable World + free cross-world pairing + search/capture/export + controlled raw reads');
    await page.close();
  }
  // Adversarial proof: failed GitHub access must not be reported as completed evidence.
  const failure=await browser.newPage({viewport:{width:1100,height:800}});
  await failure.route('https://raw.githubusercontent.com/Jozzpoly/Combat-Lab/**',route=>route.fulfill({status:403,body:'rate limit'}));
  await failure.goto('file://'+source,{waitUntil:'load'});
  await failure.locator('[data-view="material"]').click();
  await failure.locator('#enter-atelier').click();
  await failure.waitForFunction(()=>document.querySelector('#left-state')?.dataset?.error==='true'&&document.querySelector('#right-state')?.textContent?.startsWith('ODCZYTANO'),{timeout:25000});
  assert.equal(await failure.locator('#left-pin').isDisabled(),true);
  await failure.locator('#make-note').click();
  const negative=await failure.locator('#export-text').inputValue();
  assert.match(negative,/A BRAK \/ B POTWIERDZONY/);
  assert.match(await failure.locator('#left-state').innerText(),/HTTP 403/);
  assert.equal(await failure.locator('.clip').count(),0);
  console.log('PASS negative control: 403 refuses false evidence and report says A BRAK');
  await failure.close();
} finally {await browser.close();}
